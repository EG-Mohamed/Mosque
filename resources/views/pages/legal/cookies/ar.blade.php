<h2>3. إدارة موافقتك</h2>
<p>عند زيارتك الأولى يمكنك اختيار „قبول الكل“ أو „رفض الكل“ أو „الإعدادات“. لا يتم وضع أي ملفات اختيارية قبل أن تختار، والرفض سهل تمامًا مثل القبول. ويسري اختيارك على جميع النسخ اللغوية للموقع. يمكنك تغيير موافقتك أو سحبها في أي وقت عبر رابط „إعدادات ملفات تعريف الارتباط“ أسفل كل صفحة؛ وعند سحب الموافقة على التحليلات تُحذف الملفات المرتبطة بها.</p>
<p>يمكنك أيضًا حظر ملفات تعريف الارتباط أو حذفها من إعدادات متصفحك، علمًا بأن حظر الملفات الضرورية قد يمنع عمل بعض أجزاء الموقع.</p>
