<h2>1. ما هي ملفات تعريف الارتباط؟</h2>
<p>ملفات تعريف الارتباط هي ملفات نصية صغيرة يحفظها متصفحك على جهازك. وفقًا للمادة 399 من قانون الاتصالات الإلكترونية البولندي (Prawo komunikacji elektronicznej) واللائحة العامة لحماية البيانات، لا يجوز لنا تخزين معلومات على جهازك أو الوصول إليها دون موافقتك إلا إذا كان ذلك ضروريًا تمامًا لتقديم الخدمة التي طلبتها. وتتطلب جميع ملفات تعريف الارتباط الأخرى موافقتك المسبقة.</p>

